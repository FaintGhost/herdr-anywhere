#!/bin/sh
# Writes src/ui/sounds-data.ts: Herdr's two sounds (assets/sounds) as data: URIs, for the web app. A TSX bundle can't
# import an .mp3, and a web package only ships what is imported, so the browser gets the bytes inside the script.
set -eu
cd "$(dirname "$0")/.."
uri() { printf 'data:audio/mpeg;base64,%s' "$(base64 < "assets/sounds/$1" | tr -d '\n')"; }
{
  echo '// Generated by scripts/sounds-data.sh from assets/sounds (Herdr'\''s sounds, Apache-2.0). Do not edit.'
  echo "export const BLOCKED = '$(uri request.mp3)'"
  echo "export const DONE = '$(uri done.mp3)'"
} > src/ui/sounds-data.ts
