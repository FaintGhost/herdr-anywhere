#!/bin/sh
# Writes src/vendor/fonts.ts: the terminal page's fonts as base64 WOFF, since the page loads nothing from anywhere.
# Herdr's terminal font, JetBrains Mono (assets/fonts), and Herdr's icon font, Symbols Nerd Font, cut to the glyphs
# shell prompts and agents print (Powerline, Seti, Devicons, Octicons), as assets/fonts/SymbolsNerdFont-Subset.woff.
# And Noto Sans Symbols 2 cut to the symbols that are text by default (⏺ ⏸ ✔ ⚠ …), which Android otherwise draws
# from its colour emoji font: NotoSansSymbols2-Subset.unicodes lists the font's glyphs in U+2300-23FF, U+25A0-27BF
# and U+2B00-2BFF that Unicode 16's emoji-data.txt does not mark Emoji_Presentation, and its arrows and Braille (Pi's
# spinner). And Noto Sans Symbols cut to U+2300-23FF without those emoji (Claude Code's ⎿). iOS 26 has neither ⎿ nor
# Braille of its own and draws a box (e2e/ios-glyphs.sh). And Noto Sans Mono cut to the technical symbols those lack.
# Usage: scripts/terminal-fonts.sh [herdr-app checkout] [NotoSansSymbols2-Regular.ttf] [NotoSansSymbols-Regular.ttf] [NotoSansMono-Regular.ttf]
# (with a checkout, the Nerd subset is cut again from its assets/fonts/SymbolsNerdFont-Regular.ttf; with a Noto font,
# from google/fonts ofl/notosanssymbols2, ofl/notosanssymbols and ofl/notosansmono, the last two at wght 400 and wdth
# 100, its subset is cut again).
# Needs python3 with fontTools, and node.
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
fonts="$root/assets/fonts"
python3 -m fontTools.subset "$fonts/JetBrainsMono-Variable.ttf" --unicodes='*' --layout-features='*' --flavor=woff \
  --output-file="$fonts/JetBrainsMono-Variable.woff"
if [ -n "${1:-}" ]; then
  python3 -m fontTools.subset "$1/assets/fonts/SymbolsNerdFont-Regular.ttf" --no-hinting --flavor=woff \
    --unicodes='U+E0A0-E0A3,U+E0B0-E0D7,U+E5FA-E6B7,U+E700-E8EF,U+F400-F533' --output-file="$fonts/SymbolsNerdFont-Subset.woff"
fi
if [ -n "${2:-}" ]; then
  python3 -m fontTools.subset "$2" --no-hinting --flavor=woff --unicodes-file="$fonts/NotoSansSymbols2-Subset.unicodes" \
    --output-file="$fonts/NotoSansSymbols2-Subset.woff"
fi
if [ -n "${3:-}" ]; then
  python3 -m fontTools.subset "$3" --no-hinting --flavor=woff --unicodes-file="$fonts/NotoSansSymbols-Subset.unicodes" \
    --output-file="$fonts/NotoSansSymbols-Subset.woff"
fi
if [ -n "${4:-}" ]; then
  python3 -m fontTools.subset "$4" --no-hinting --flavor=woff --unicodes-file="$fonts/NotoSansMono-Subset.unicodes" \
    --output-file="$fonts/NotoSansMono-Subset.woff"
fi
node -e '
const fs = require("fs"), [dir, out] = process.argv.slice(1)
const b64 = (f) => fs.readFileSync(dir + "/" + f).toString("base64")
fs.writeFileSync(out, "// Generated by scripts/terminal-fonts.sh from assets/fonts (OFL-1.1 and MIT, see NOTICE). Do not edit.\n"
  + "export const MONO_WOFF = " + JSON.stringify(b64("JetBrainsMono-Variable.woff")) + "\n"
  + "export const SYMBOLS_WOFF = " + JSON.stringify(b64("SymbolsNerdFont-Subset.woff")) + "\n"
  + "export const SYMBOLS2_WOFF = " + JSON.stringify(b64("NotoSansSymbols2-Subset.woff")) + "\n"
  + "export const SYMBOLS1_WOFF = " + JSON.stringify(b64("NotoSansSymbols-Subset.woff")) + "\n"
  + "export const NOTO_MONO_WOFF = " + JSON.stringify(b64("NotoSansMono-Subset.woff")) + "\n")
' "$fonts" "$root/src/vendor/fonts.ts"
echo "wrote $root/src/vendor/fonts.ts"
