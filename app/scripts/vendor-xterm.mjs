#!/usr/bin/env node
// Writes src/vendor/xterm.ts: xterm.js, its FitAddon, WebglAddon (it draws box drawing and block characters itself, so
// they join across rows at Herdr's line height, as the desktop's sprites do) as strings for the terminal's web page (src/terminal-page.ts).
// herdr-core paints screens as xterm-256color VT, which xterm.js 6 draws.
// Usage: node scripts/vendor-xterm.mjs <work dir>   (npm pack checks each tarball against the registry's integrity,
// and this script against the pins below.)
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PINS = {
  '@xterm/xterm@6.0.0': 'sha512-TQwDdQGtwwDt+2cgKDLn0IRaSxYu1tSUjgKarSDkUM0ZNiSRXFpjxEsvc/Zgc5kq5omJ+V0a8/kIM2WD3sMOYg==',
  '@xterm/addon-fit@0.11.0': 'sha512-jYcgT6xtVYhnhgxh3QgYDnnNMYTcf8ElbxxFzX0IZo+vabQqSPAjC3c1wJrKB5E19VwQei89QCiZZP86DCPF7g==',
  '@xterm/addon-webgl@0.19.0': 'sha512-b3fMOsyLVuCeNJWxolACEUED0vm7qC0cy4wRvf3oURSzDTYVQiGPhTnhWZwIHdvC48Y+oLhvYXnY4XDXPoJo6A==',
}
const work = process.argv[2]
if (!work) { console.error('usage: node scripts/vendor-xterm.mjs <work dir>'); process.exit(2) }
mkdirSync(work, { recursive: true })
const packed = JSON.parse(execFileSync('npm', ['pack', ...Object.keys(PINS), '--json', '--ignore-scripts'], { cwd: work, encoding: 'utf8' }))
const dirs = {}
for (const [spec, integrity] of Object.entries(PINS)) {
  const p = packed.find((x) => `${x.name}@${x.version}` === spec)
  if (!p || p.integrity !== integrity) throw new Error(`${spec}: integrity ${p?.integrity} does not match the pin`)
  const dir = join(work, p.filename.replace(/\.tgz$/, ''))
  mkdirSync(dir, { recursive: true })
  execFileSync('tar', ['-xzf', join(work, p.filename), '-C', dir])
  dirs[p.name] = join(dir, 'package')
}
const read = (name, path) => readFileSync(join(dirs[name], path), 'utf8')
const parts = { XTERM_JS: read('@xterm/xterm', 'lib/xterm.js'), XTERM_CSS: read('@xterm/xterm', 'css/xterm.css'), FIT_JS: read('@xterm/addon-fit', 'lib/addon-fit.js'),
  WEBGL_JS: read('@xterm/addon-webgl', 'lib/addon-webgl.js') }
for (const [k, v] of Object.entries(parts)) if (/<\/(script|style)/i.test(v)) throw new Error(`${k} would close its inline tag`)
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'vendor')
mkdirSync(out, { recursive: true })
writeFileSync(join(out, 'xterm.ts'), `// Generated by scripts/vendor-xterm.mjs from ${Object.keys(PINS).join(' and ')} (MIT, see xterm-LICENSE). Do not edit.\n`
  + Object.entries(parts).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)}\n`).join(''))
writeFileSync(join(out, 'xterm-LICENSE'), Object.keys(PINS).map((spec) => spec.replace(/@[^@]+$/, '')).map((n) => `${n}\n\n${read(n, 'LICENSE')}`).join('\n'))
console.log(`wrote ${join(out, 'xterm.ts')}`)
